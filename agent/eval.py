"""Routing eval: does the agent pick the right metric, dimensions, filters and period?

The prose is not scored. For each question in eval_questions.yml the last consultar_metrica
call that worked is compared with the expected one, field by field, after the compiler
normalizes both (build_question), so equivalent periods and dimension orders match. A
trap question passes only when the agent rejects it.

    python -m agent.eval                 # compile only, no BigQuery needed
    python -m agent.eval --live          # also run the queries
    python -m agent.eval --only trap_    # questions whose id starts with trap_

Each run is saved to agent/eval_runs/ (ignored by git); --report writes the markdown
summary to docs/agent_eval.md.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import time
from pathlib import Path
from typing import Any

import yaml

from agent.core import DEFAULT_MODEL, REPO_ROOT, ask, normalize_call
from semantic.compiler import Question, SemanticError, _default_spec, build_question

QUESTIONS_PATH = Path(__file__).resolve().parent / "eval_questions.yml"
RUNS_DIR = Path(__file__).resolve().parent / "eval_runs"
REPORT_PATH = REPO_ROOT / "docs" / "agent_eval.md"
FIELDS = ("metric", "dimensions", "filters", "period")
RATE_LIMIT_WAIT = 60  # seconds; free tiers reset their quota per minute


def load_questions(path: Path = QUESTIONS_PATH) -> list[dict[str, Any]]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))["questions"]


def _key(q: Question) -> dict[str, Any]:
    """The comparable parts of a validated question."""
    return {
        "metric": q.metric.name,
        "dimensions": sorted(d.name for d in q.dimensions),
        "filters": {d.name: list(v) for d, v in q.filters},
        "period": [f"{q.period[0]:%Y-%m}", f"{q.period[1]:%Y-%m}"],
    }


def expected_key(expect: dict[str, Any]) -> dict[str, Any]:
    return _key(
        build_question(
            expect["metric"],
            expect.get("dimensions", []),
            expect.get("filters"),
            expect.get("period"),
        )
    )


def score(item: dict[str, Any], status: str, call: dict[str, Any] | None) -> dict[str, Any]:
    """Field-by-field result of one question."""
    if item.get("reject"):
        return {"kind": "trap", "pass": status == "rejected", "fields": {}}

    want = expected_key(item["expect"])
    got = None
    if status == "answered" and call is not None:
        try:
            got = _key(build_question(**normalize_call(call)))
        except SemanticError:
            got = None
    fields = {f: got is not None and got[f] == want[f] for f in FIELDS}
    return {
        "kind": "answer",
        "pass": all(fields.values()),
        "fields": fields,
        "want": want,
        "got": got,
    }


def summarize(results: list[dict[str, Any]]) -> dict[str, Any]:
    answers = [r for r in results if r["score"]["kind"] == "answer"]
    traps = [r for r in results if r["score"]["kind"] == "trap"]
    return {
        "questions": len(results),
        "passed": sum(r["score"]["pass"] for r in results),
        "answerable": len(answers),
        "exact": sum(r["score"]["pass"] for r in answers),
        "fields": {f: sum(r["score"]["fields"][f] for r in answers) for f in FIELDS},
        "false_rejections": sum(r["status"] != "answered" for r in answers),
        "traps": len(traps),
        "traps_rejected": sum(r["score"]["pass"] for r in traps),
    }


def _pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "-"


def report_markdown(run: dict[str, Any]) -> str:
    s = run["summary"]
    lines = [
        "# Agent routing eval",
        "",
        f"Model `{run['model']}`, {run['started'][:16].replace('T', ' ')} UTC, "
        f"{'queries run on BigQuery' if run['live'] else 'SQL compiled, not run'}. "
        "Generated by `python -m agent.eval --report`; the questions are in "
        "[agent/eval_questions.yml](../agent/eval_questions.yml).",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| All questions right | {_pct(s['passed'], s['questions'])} |",
        f"| Answerable, exact call | {_pct(s['exact'], s['answerable'])} |",
    ]
    for f in FIELDS:
        lines.append(f"| Answerable, {f} right | {_pct(s['fields'][f], s['answerable'])} |")
    lines += [
        f"| Answerable but rejected | {s['false_rejections']} |",
        f"| Traps rejected | {_pct(s['traps_rejected'], s['traps'])} |",
        "",
        "## Misses",
        "",
    ]
    misses = [r for r in run["results"] if not r["score"]["pass"]]
    if not misses:
        lines.append("None.")
    for r in misses:
        sc = r["score"]
        if sc["kind"] == "trap":
            lines.append(f"- `{r['id']}`: answered a trap with `{json.dumps(r['call'])}`.")
        elif sc["got"] is None:
            lines.append(f"- `{r['id']}`: {r['status']} - {r['text'][:160]}")
        else:
            wrong = [f for f in FIELDS if not sc["fields"][f]]
            detail = "; ".join(f"{f} {sc['got'][f]} instead of {sc['want'][f]}" for f in wrong)
            lines.append(f"- `{r['id']}`: {detail}.")
    return "\n".join(lines) + "\n"


def run_eval(
    model: str | None = None,
    live: bool = False,
    only: str | None = None,
    pause: float = 5.0,
) -> dict[str, Any]:
    items = [q for q in load_questions() if not only or q["id"].startswith(only)]
    for q in items:  # a typo in the expectations fails before spending any API calls
        if not q.get("reject"):
            expected_key(q["expect"])

    spec = _default_spec()
    run: dict[str, Any] = {
        "model": model or DEFAULT_MODEL,
        "live": live,
        "started": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "results": [],
    }
    for i, item in enumerate(items):
        if i:
            time.sleep(pause)  # free tiers count requests per minute
        for attempt in range(3):
            try:
                a = ask(item["question"], model=model, spec=spec, execute=live)
                status, text, call, model_used = a.status, a.text, a.call, a.model
                tools = [t.__dict__ for t in a.tool_calls]
                break
            except Exception as e:  # provider errors count as misses, the run goes on
                status, text, call, model_used, tools = "error", repr(e), None, model, []
                if "RateLimit" not in type(e).__name__ or attempt == 2:
                    break
                time.sleep(RATE_LIMIT_WAIT)  # per-minute quota: wait for the window
        run["model"] = model_used or run["model"]
        result = {
            "id": item["id"],
            "question": item["question"],
            "status": status,
            "text": text,
            "call": call,
            "tool_calls": tools,
            "score": score(item, status, call),
        }
        run["results"].append(result)
        mark = "ok " if result["score"]["pass"] else "MISS"
        print(f"{mark} {item['id']:<40} {status:<9} {json.dumps(call, ensure_ascii=False) if call else text[:90]}")

    run["summary"] = summarize(run["results"])
    return run


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--model", help=f"litellm model id (default {DEFAULT_MODEL})")
    parser.add_argument("--live", action="store_true", help="run the queries on BigQuery")
    parser.add_argument("--only", help="only questions whose id starts with this")
    parser.add_argument("--pause", type=float, default=5.0, help="seconds between questions")
    parser.add_argument("--report", action="store_true", help=f"write {REPORT_PATH.name}")
    args = parser.parse_args(argv)

    run = run_eval(args.model, args.live, args.only, args.pause)
    RUNS_DIR.mkdir(exist_ok=True)
    stamp = run["started"][:16].replace(":", "").replace("-", "")
    out = RUNS_DIR / f"{stamp}_{run['model'].replace('/', '_')}.json"
    out.write_text(json.dumps(run, indent=2, ensure_ascii=False), encoding="utf-8")

    s = run["summary"]
    print(
        f"\n{s['passed']}/{s['questions']} right; exact calls {s['exact']}/{s['answerable']}; "
        + ", ".join(f"{f} {s['fields'][f]}" for f in FIELDS)
        + f"; traps rejected {s['traps_rejected']}/{s['traps']}; "
        f"false rejections {s['false_rejections']}. Saved {out.relative_to(REPO_ROOT)}"
    )
    if args.report:
        REPORT_PATH.write_text(report_markdown(run), encoding="utf-8")
        print(f"Report: {REPORT_PATH.relative_to(REPO_ROOT)}")
    return 0 if s["passed"] == s["questions"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
